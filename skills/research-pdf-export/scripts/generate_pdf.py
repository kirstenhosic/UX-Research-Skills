def build_cover(title, subtitle=None, description=None, study_date=None, team=None):
    """Build cover page story elements. Only title is required.

    All caller-supplied strings are XML-escaped before going to ReportLab
    so a literal `&` in a CLI argument (e.g. --team "AI & Research")
    doesn't crash the build."""
    story = []
    story.append(Spacer(1, 1.7 * inch))
    story.append(Paragraph(escape_xml(title), STYLES.cover_title))
    if subtitle:
        story.append(Paragraph(escape_xml(subtitle), STYLES.cover_subtitle))
    if description:
        story.append(Paragraph(escape_xml(description), STYLES.cover_desc))

    # Only add metadata section if there's metadata to show
    has_metadata = study_date or team
    if has_metadata:
        # Push metadata toward bottom
        story.append(Spacer(1, 2.5 * inch))
        if study_date:
            story.append(Paragraph("Research date", STYLES.cover_meta_label))
            story.append(Paragraph(escape_xml(study_date), STYLES.cover_meta_value))
        if team:
            story.append(Paragraph("Team", STYLES.cover_meta_label))
            story.append(Paragraph(escape_xml(team), STYLES.cover_meta_value))

    story.append(PageBreak())
    return story


def build_toc(toc_titles):
    """Build the accent-numbered table of contents page from a list of
    titles. Returns [] when toc_titles is empty (caller decides whether the
    Contents block was found in the markdown)."""
    if not toc_titles:
        return []

    story = []
    story.append(Spacer(1, 0.3 * inch))
    story.append(AccentBar(40, 3))
    story.append(Spacer(1, 6))
    story.append(Paragraph("Contents", STYLES.toc_title))
    story.append(ThinRule(color=INK, thickness=0.75))
    story.append(Spacer(1, 12))

    for idx, title in enumerate(toc_titles, 1):
        # Strip authored leading numbering ("1. Foo") for the display only —
        # the accent "01" badge replaces it.
        display = re.sub(r'^\s*\d+\.\s*', '', title).strip()
        num = f"{idx:02d}"
        row = [[Paragraph(num, STYLES.toc_num),
                Paragraph(escape_xml(display), STYLES.toc_text)]]
        t = Table(row, colWidths=[0.6 * inch, 5.5 * inch])
        t.setStyle(TableStyle([
            ('VALIGN',     (0, 0), (-1, -1), 'MIDDLE'),
            ('FONTNAME',   (0, 0), (-1, -1), font("Light")),
            ('TOPPADDING', (0, 0), (-1, -1), 0),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
            ('LEFTPADDING', (0, 0), (-1, -1), 0),
            ('RIGHTPADDING', (0, 0), (-1, -1), 0),
            ('LINEBELOW',  (0, 0), (-1, -1), 0.3, BASE_LIGHTER),
        ]))
        story.append(t)

    story.append(PageBreak())
    return story


def _default_title_from_path(md_path):
    base = os.path.splitext(os.path.basename(md_path))[0]
    return base.replace("-", " ").replace("_", " ").strip().title() or "Research Report"


def build_document(md_path, output_path, cover=False, title=None, subtitle=None,
                   description=None, study_date=None, team=None, font_dir=None,
                   footer_note=None):
    # Register fonts here (not at import time) so --help and argparse
    # errors never touch the TTF files, then build every style through
    # font() so the names match what was registered.
    register_fonts(font_dir)
    build_styles()

    with open(md_path, "r", encoding="utf-8") as f:
        md_text = f.read()

    md_text = strip_emoji(md_text)

    # Resolve metadata strictly from CLI args -- no markdown sniffing.
    document_title = title or _default_title_from_path(md_path)
    report_date = study_date or datetime.now().strftime("%B %Y")

    # Preprocessing pipeline: strip the boilerplate blocks out of the source
    # before parse_markdown sees them, so the parser stays dumb and renders
    # whatever's left as continuous body content.
    toc_titles, md_text = extract_and_strip_toc(md_text)
    md_text = strip_cover_block(md_text)
    if cover:
        md_text = strip_h1_if_matches_cover(md_text, document_title)

    # Body story
    content_story = parse_markdown(md_text, document_title)
    content_story = suppress_leading_rule(content_story)

    # Compose the full document story
    story = []

    if cover:
        story.extend(build_cover(
            document_title,
            subtitle,
            description,
            study_date or report_date,
            team,
        ))

    story.extend(build_toc(toc_titles))
    story.extend(content_story)

    # Build PDF
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        leftMargin=LEFT_MARGIN,
        rightMargin=RIGHT_MARGIN,
        topMargin=TOP_MARGIN + 0.15 * inch,
        bottomMargin=BOTTOM_MARGIN,
        title=document_title,
        author=team or "",
        # The canvas's starting font, so no page references a face that
        # font() didn't choose.
        initialFontName=font("Regular"),
    )

    # Bind document_title / report_date into the content footer callback
    # via partial so we don't reach for module globals.
    content_cb = partial(
        content_page_cb,
        document_title=document_title,
        report_date=report_date,
        footer_note=footer_note,
    )
    first_page_cb = cover_page_cb if cover else content_cb

    try:
        print(f"Building PDF with {len(story)} elements...", file=sys.stderr, flush=True)
        doc.build(story, onFirstPage=first_page_cb, onLaterPages=content_cb)
        print(f"PDF generated successfully: {output_path}")
        return output_path
    except Exception as e:
        print(f"ERROR during PDF build: {e}", file=sys.stderr)
        raise


