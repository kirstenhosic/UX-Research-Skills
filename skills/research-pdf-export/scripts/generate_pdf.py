# ============================================================
# 1. FONTS
# ============================================================
# Public Sans ships with the skill in <skill>/assets/fonts/ (SIL Open Font
# License 1.1; OFL.txt and LICENSE.md sit beside the TTFs). Nothing is
# downloaded. Registration is deferred until build_document() runs so that
# `--help` and argparse errors never touch the TTF files.
#
# Every font name the renderer uses goes through font(face). After
# register_fonts() it returns "PublicSans-<face>" when all ten faces loaded,
# or the matching Helvetica face when any of them failed.

DEFAULT_FONT_DIR = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "assets", "fonts"
))

FONT_FACES = ["Light", "Regular", "Medium", "SemiBold", "Bold",
              "Italic", "LightItalic", "MediumItalic", "SemiBoldItalic", "BoldItalic"]

# Built-in stand-in for each face when Public Sans can't be loaded.
HELVETICA_FALLBACK = {
    "Light":          "Helvetica",
    "Regular":        "Helvetica",
    "Medium":         "Helvetica-Bold",
    "SemiBold":       "Helvetica-Bold",
    "Bold":           "Helvetica-Bold",
    "Italic":         "Helvetica-Oblique",
    "LightItalic":    "Helvetica-Oblique",
    "MediumItalic":   "Helvetica-BoldOblique",
    "SemiBoldItalic": "Helvetica-BoldOblique",
    "BoldItalic":     "Helvetica-BoldOblique",
}

# Inline <b>, <i>, <b><i> mapping for each base face a style uses:
# base -> (normal, bold, italic, boldItalic). Bold is always Bold (700);
# italic keeps the base weight. The Italic base face (callouts) resolves
# through the Regular family, whose italic member it is. The Helvetica
# fallback needs no registration: ReportLab maps that family built in.
FONT_FAMILIES = {
    "Light":    ("Light",    "Bold", "LightItalic",    "BoldItalic"),
    "Regular":  ("Regular",  "Bold", "Italic",         "BoldItalic"),
    "Medium":   ("Medium",   "Bold", "MediumItalic",   "BoldItalic"),
    "SemiBold": ("SemiBold", "Bold", "SemiBoldItalic", "BoldItalic"),
}

# Face -> registered font name. Starts on Helvetica so nothing can reference
# an unregistered name; register_fonts() switches it to Public Sans.
_active_faces = dict(HELVETICA_FALLBACK)


def font(face):
    """The font name to use for a Public Sans face ("Light", "SemiBold", ...):
    "PublicSans-<face>" when Public Sans is registered, else its Helvetica
    stand-in. The single place font names are decided."""
    return _active_faces[face]


def register_fonts(font_dir=None):
    """Register the ten Public Sans faces from font_dir (default: the fonts
    bundled in <skill>/assets/fonts/) plus the inline bold/italic mapping for
    every base face. All-or-nothing: if any face fails, font() resolves every
    face to Helvetica and one warning goes to stderr. Returns True when
    Public Sans is active."""
    global _active_faces
    font_dir = os.path.expanduser(font_dir) if font_dir else DEFAULT_FONT_DIR

    missing = [f"PublicSans-{face}.ttf" for face in FONT_FACES
               if not os.path.isfile(os.path.join(font_dir, f"PublicSans-{face}.ttf"))]
    if len(missing) == len(FONT_FACES):
        problem = "no PublicSans-*.ttf files found"
    elif missing:
        problem = "missing " + ", ".join(missing)
    else:
        problem = None
        try:
            for face in FONT_FACES:
                pdfmetrics.registerFont(TTFont(
                    f"PublicSans-{face}",
                    os.path.join(font_dir, f"PublicSans-{face}.ttf"),
                ))
            # Families go after every registerFont call: registering a TTF
            # resets that face's own mapping.
            for base, (normal, bold, italic, bold_italic) in FONT_FAMILIES.items():
                pdfmetrics.registerFontFamily(
                    f"PublicSans-{base}",
                    normal=f"PublicSans-{normal}",
                    bold=f"PublicSans-{bold}",
                    italic=f"PublicSans-{italic}",
                    boldItalic=f"PublicSans-{bold_italic}",
                )
        except Exception as e:
            problem = str(e)

    if problem:
        _active_faces = dict(HELVETICA_FALLBACK)
        print(
            f"WARNING: Public Sans could not be loaded from {font_dir} ({problem}). "
            "Falling back to Helvetica: the PDF will render, but not in Public Sans.",
            file=sys.stderr,
        )
        return False

    _active_faces = {face: f"PublicSans-{face}" for face in FONT_FACES}
    return True

