def strip_emoji(text):
    emoji_pattern = re.compile(
        "["
        "\U0001F600-\U0001F64F"
        "\U0001F300-\U0001F5FF"
        "\U0001F680-\U0001F6FF"
        "\U0001F1E0-\U0001F1FF"
        "\U00002702-\U000027B0"
        "\U000024C2-\U0001F251"
        "\U0001f926-\U0001f937"
        "\U00010000-\U0010ffff"
        "\u200d"
        "\u2640-\u2642"
        "\ufe0f"
        "\u2600-\u26FF"
        "\u2700-\u27BF"
        "\u23E9-\u23F3"
        "\u23F8-\u23FA"
        "\u25AA-\u25FE"
        "\u200C-\u200D"
        "\u2934-\u2935"
        "\u3030\u303D"
        "\uFE00-\uFE0F"
        "]+",
        flags=re.UNICODE,
    )
    return emoji_pattern.sub("", text)


