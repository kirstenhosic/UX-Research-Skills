class AccentBar(Flowable):
    def __init__(self, width=40, height=3):
        Flowable.__init__(self)
        self._bar_w = width
        self._bar_h = height
        self.width = width
        self.height = height + 4

    def draw(self):
        self.canv.setFillColor(PRIMARY)
        self.canv.rect(0, 2, self._bar_w, self._bar_h, fill=1, stroke=0)


class ThinRule(Flowable):
    def __init__(self, width=None, color=None, thickness=0.5):
        Flowable.__init__(self)
        self._rule_w = width or CONTENT_W
        self._color = color or BASE_LIGHTER
        self._thickness = thickness
        self.width = self._rule_w
        self.height = 4

    def draw(self):
        self.canv.setStrokeColor(self._color)
        self.canv.setLineWidth(self._thickness)
        self.canv.line(0, 2, self._rule_w, 2)


class CalloutBox(Flowable):
    def __init__(self, quote_text, attribution_text=None, width=None):
        Flowable.__init__(self)
        self.quote_text = quote_text
        self.attribution_text = attribution_text
        self._width = width or CONTENT_W
        self._calc_height()

    def _calc_height(self):
        inner_w = self._width - 24
        self._quote_para = Paragraph(self.quote_text, STYLES.callout)
        qw, qh = self._quote_para.wrap(inner_w, 1000)
        self._quote_h = qh
        self._attr_h = 0
        self._attr_para = None
        if self.attribution_text:
            self._attr_para = Paragraph(
                "\u2014 " + self.attribution_text, STYLES.callout_attribution
            )
            aw, ah = self._attr_para.wrap(inner_w, 1000)
            self._attr_h = ah
        self.height = 10 + self._quote_h + (4 if self._attr_para else 0) + self._attr_h + 10
        self.width = self._width

    def wrap(self, availWidth, availHeight):
        self._width = availWidth
        self._calc_height()
        return (self._width, self.height)

    def draw(self):
        canvas = self.canv
        canvas.setFillColor(PRIMARY_LIGHTER)
        canvas.roundRect(0, 0, self._width, self.height, 3, fill=1, stroke=0)
        canvas.setFillColor(PRIMARY)
        canvas.rect(0, 0, 3, self.height, fill=1, stroke=0)
        y = self.height - 10 - self._quote_h
        self._quote_para.drawOn(canvas, 12, y)
        if self._attr_para:
            y = y - 4 - self._attr_h
            self._attr_para.drawOn(canvas, 12, y)


