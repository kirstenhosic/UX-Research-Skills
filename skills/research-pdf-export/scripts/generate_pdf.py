# Optional cover logo. No logo ships with the skill: a team that wants its
# own mark on the cover drops an SVG at <skill>/assets/logo.svg (the script
# lives in <skill>/scripts/). If the file is absent, the cover renders
# without a logo.
LOGO_PATH = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "assets", "logo.svg"
))


def cover_page_cb(canvas, doc):
    canvas.saveState()
    # Background fill
    canvas.setFillColor(PRIMARY_DARKER)
    canvas.rect(0, 0, PAGE_W, PAGE_H, fill=1, stroke=0)
    # Accent line
    canvas.setStrokeColor(ACCENT_COOL)
    canvas.setLineWidth(1)
    accent_y = PAGE_H - 122
    canvas.line(LEFT_MARGIN, accent_y, LEFT_MARGIN + CONTENT_W, accent_y)
    # Logo (bottom-right)
    if os.path.exists(LOGO_PATH):
        from reportlab.graphics import renderPDF
        try:
            from svglib.svglib import svg2rlg
            drawing = svg2rlg(LOGO_PATH)
            if drawing:
                scale_w = 45 / drawing.width
                scale_h = 100 / drawing.height
                scale = min(scale_w, scale_h)
                drawing.width *= scale
                drawing.height *= scale
                drawing.scale(scale, scale)
                logo_x = PAGE_W - 57 - drawing.width
                logo_y = 57
                renderPDF.draw(drawing, canvas, logo_x, logo_y)
        except ImportError:
            pass  # svglib not installed, skip logo
        except Exception as e:
            # A team-supplied SVG svglib can't parse must not sink the build.
            print(f"WARNING: Could not draw cover logo {LOGO_PATH}: {e}", file=sys.stderr)
    canvas.restoreState()


def content_page_cb(canvas, doc, document_title="", report_date="", footer_note=None):
    """Footer-only page decoration. Document title, report date, and the
    optional footer note are bound by the caller via functools.partial so
    we don't lean on globals."""
    canvas.saveState()
    # Footer only -- no top header. Page number lives on the footer right.
    canvas.setStrokeColor(BASE_LIGHTER)
    canvas.setLineWidth(0.5)
    canvas.line(LEFT_MARGIN, BOTTOM_MARGIN - 0.15 * inch, PAGE_W - RIGHT_MARGIN, BOTTOM_MARGIN - 0.15 * inch)
    canvas.setFont(font("Regular"), 6.5)
    canvas.setFillColor(BASE_DARK)
    footer_left = f"{document_title}  |  {report_date}"
    if footer_note:
        footer_right = f"{footer_note}  ·  Page {doc.page}"
    else:
        footer_right = f"Page {doc.page}"
    canvas.drawString(LEFT_MARGIN, BOTTOM_MARGIN - 0.35 * inch, footer_left)
    canvas.drawRightString(PAGE_W - RIGHT_MARGIN, BOTTOM_MARGIN - 0.35 * inch, footer_right)
    canvas.restoreState()


